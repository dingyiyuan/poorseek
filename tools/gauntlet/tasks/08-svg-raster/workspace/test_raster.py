from raster import rasterize


def test_square():
    img = rasterize("M1 1 H4 V3 H1 Z", 5, 4)
    assert img == [".....", ".###.", ".###.", "....."]


def test_cubic_blob():
    img = rasterize("M2 10 C2 2 10 2 10 10 Z", 12, 12)
    assert img == ["............", "............", "............", "............",
                   "....####....", "...######...", "...######...", "..########..",
                   "..########..", "..########..", "............", "............"]


def test_quadratic_relative():
    img = rasterize("m2,10 q4,-8 8,0 z", 12, 12)
    assert img == ["............", "............", "............", "............",
                   "............", "............", ".....##.....", "....####....",
                   "...######...", "..########..", "............", "............"]
